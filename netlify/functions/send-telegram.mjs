export default async (req) => {

  if (req.method !== "POST") {

    return new Response(
      JSON.stringify({
        error: "Method not allowed"
      }),
      {
        status: 405,
        headers: {
          "Content-Type": "application/json"
        }
      }
    );

  }


  try {

    const data = await req.json();


    /*
      Telegram credentials stay on the Netlify server.

      They are NEVER sent to the browser.
    */

    const botToken =
      process.env.TELEGRAM_BOT_TOKEN;

    const chatId =
      process.env.TELEGRAM_CHAT_ID;


    if (!botToken || !chatId) {

      console.error(
        "Telegram environment variables are missing."
      );


      return new Response(
        JSON.stringify({
          error:
            "Telegram configuration missing"
        }),
        {
          status: 500,
          headers: {
            "Content-Type":
              "application/json"
          }
        }
      );

    }


    const message =

      "🔔 NEW HVAC DEMO LEAD\n\n" +

      "👤 Name: " +
      (data.name || "N/A") +
      "\n" +

      "📞 Phone: " +
      (data.phone || "N/A") +
      "\n" +

      "📧 Email: " +
      (data.email || "N/A") +
      "\n" +

      "📍 Address: " +
      (data.address || "N/A") +
      "\n\n" +

      "🛠️ Service: " +
      (data.service || "N/A") +
      "\n" +

      "🌡️ Situation: " +
      (data.situation || "N/A") +
      "\n" +

      "⚡ Urgency: " +
      (data.urgency || "N/A") +
      "\n" +

      "📐 System Size: " +
      (data.systemSize || "N/A") +
      "\n" +

      "💎 Efficiency: " +
      (data.efficiency || "N/A") +
      "\n" +

      "💰 Demo Estimate: " +
      (data.estimatedRange || "N/A") +
      "\n" +

      "🗓️ Timeframe: " +
      (data.timeline || "N/A") +
      "\n" +

      "📝 Details: " +
      (data.details || "N/A") +
      "\n\n" +

      "🕒 Time: " +
      (data.timestamp || "N/A") +
      "\n\n" +

      "This is a demonstration lead generated by the Carolina Comfort HVAC demo.";


    const telegramResponse =

      await fetch(

        `https://api.telegram.org/bot${botToken}/sendMessage`,

        {

          method: "POST",

          headers: {
            "Content-Type":
              "application/json"
          },

          body: JSON.stringify({

            chat_id: chatId,

            text: message

          })

        }

      );


    const telegramResult =
      await telegramResponse.json();


    if (
      !telegramResponse.ok ||
      !telegramResult.ok
    ) {

      console.error(
        "Telegram error:",
        telegramResult
      );


      return new Response(
        JSON.stringify({
          error:
            "Telegram notification failed"
        }),
        {
          status: 502,
          headers: {
            "Content-Type":
              "application/json"
          }
        }
      );

    }


    return new Response(
      JSON.stringify({
        success: true
      }),
      {
        status: 200,
        headers: {
          "Content-Type":
            "application/json"
        }
      }
    );


  } catch (error) {

    console.error(
      "Function error:",
      error
    );


    return new Response(
      JSON.stringify({
        error:
          "Invalid request"
      }),
      {
        status: 400,
        headers: {
          "Content-Type":
            "application/json"
        }
      }
    );

  }

};